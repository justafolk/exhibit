#!/usr/bin/env python3
"""Secret-free, per-checkout environments. No automatic deletion or secret copying."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import socket
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]

def identity(path):
    return hashlib.sha256(str(Path(path).resolve()).encode()).hexdigest()[:8]

def ports_for(path):
    slot = int(identity(path), 16) % 10000
    return (20000 + slot, 30000 + slot, 40000 + slot)

def available(ports):
    for port in ports:
        with socket.socket() as sock:
            try:
                sock.bind(('127.0.0.1', port))
            except OSError:
                return False
    return True

def env(path):
    target = path / '.env'
    if target.exists():
        print(f'Keeping existing {target}')
        return
    ports = ports_for(path)
    # Detect live collisions and environments in sibling worktrees before choosing.
    used = set()
    result = subprocess.run(['git', '-C', str(path), 'worktree', 'list', '--porcelain'], capture_output=True, text=True)
    for line in result.stdout.splitlines():
        if line.startswith('worktree '):
            sibling = Path(line[9:]) / '.env'
            if sibling.exists():
                for entry in sibling.read_text().splitlines():
                    if re.match(r'^(WEB|API|DB)_PORT=\d+$', entry):
                        used.add(int(entry.split('=')[1]))
    for offset in range(10000):
        candidate = tuple(start + (ports[0] - 20000 + offset) % 10000 for start in (20000, 30000, 40000))
        if not used.intersection(candidate) and available(candidate):
            ports = candidate
            break
    else:
        raise RuntimeError('No free worktree port set available')
    web, api, db = ports
    values = {
        'COMPOSE_PROJECT_NAME': f'exhibit_{identity(path)}',
        'WEB_PORT': str(web), 'API_PORT': str(api), 'DB_PORT': str(db),
        'POSTGRES_USER': 'exhibit', 'POSTGRES_PASSWORD': 'exhibit_local_only',
        'POSTGRES_DB': 'exhibit',
        'DATABASE_URL': f'postgres://exhibit:exhibit_local_only@127.0.0.1:{db}/exhibit?sslmode=disable',
        'EXHIBIT_STORE': 'demo',
        'EXHIBIT_COOKIE_SECURE': 'false',
    }
    with target.open('x') as output:
        output.write('# Local development only. Generated by scripts/worktree.py.\n')
        output.write(''.join(f'{key}={value}\n' for key, value in values.items()))
    target.chmod(0o600)
    print(f'Created {target}; web={web}, api={api}, db={db}')

def create(name):
    if not re.fullmatch(r'[a-z0-9][a-z0-9-]{0,47}', name or ''):
        raise ValueError('NAME must use 1–48 lowercase letters, digits or hyphens')
    common = subprocess.check_output(['git', '-C', str(ROOT), 'rev-parse', '--path-format=absolute', '--git-common-dir'], text=True).strip()
    main_root = Path(common).parent
    destination = main_root.parent / f'{main_root.name}-worktrees' / name
    destination.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(['git', '-C', str(ROOT), 'worktree', 'add', '-b', f'agent/{name}', str(destination), 'HEAD'], check=True)
    env(destination)
    print(f'Next: cd {destination} && make bootstrap && make dev')

def doctor():
    result = {tool: shutil.which(tool) for tool in ['git', 'node', 'npm', 'go', 'docker', 'gh', 'make']}
    result['checkout'] = str(ROOT)
    result['identity'] = identity(ROOT)
    result['environment_exists'] = (ROOT / '.env').exists()
    print(json.dumps(result, indent=2))
    if not all(result[tool] for tool in ['git', 'node', 'npm', 'go', 'make']):
        sys.exit(1)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['env', 'create', 'doctor'])
    parser.add_argument('name', nargs='?')
    args = parser.parse_args()
    try:
        {'env': lambda: env(ROOT), 'create': lambda: create(args.name), 'doctor': doctor}[args.command]()
    except (ValueError, RuntimeError, subprocess.CalledProcessError) as error:
        print(str(error), file=sys.stderr)
        sys.exit(1)
